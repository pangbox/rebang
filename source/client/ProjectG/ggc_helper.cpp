bool GGC_Helper::StackError(unsigned long error, bool bCritical)
{
	if (error == 1877)
		return false;
	if (bCritical)
	{
		switch (error)
		{
		case 110:
		case 115:
		case 114:
		case 124:
		case 153:
		case 120:
		case 150:
		case 155:
		case 170:
		case 200:
		case 350:
		case 380:
		case 340:
		case 360:
		case 112:
			return StackCriticalError(error);
		default:
			return StackCriticalError(error);
		}
	}
	else
	{
		switch (error)
		{
		case 1001:
		case 1002:
		case 1011:
		case 1012:
		case 1013:
		case 1014:
		case 1015:
			return StackCriticalError(error);
		}
		return true;
	}
}

bool GGC_Helper::StackApprovableError(unsigned long error)
{
	m_approvableErrors.push_back(error);
	return true;
}

bool GGC_Helper::StackCriticalError(unsigned long error)
{
	m_criticalErrors.push_back(error);
	if (!g_pFresh)
	{
		ForceShutdown();
		std::string message;
		GetErrorMessage(error, message);
		MessageBox(NULL, message.c_str(), "PangYa", MB_OK);
	}
	else
	{
		if (!m_pDlg)
		{
			m_pDlg = CreateForm<GGC_Dlg>(g_pFresh->GetManager(), this,
				"GameGuard", NULL);
			if (!m_pDlg)
				ForceShutdown();
			m_pDlg->Open((FRESH_PFN_RESULT)&GGC_Helper::OnGameGuardDlgResult,
				576);
		}
		else
			ForceShutdown();
	}
	return false;
}

void GGC_Helper::GetErrorMessage(unsigned long error, std::string& message)
{
	while (true)
	{
		if (m_errorMessages.find(error) != m_errorMessages.end())
			break;
		m_errorMessages[error] =
			"\xb0\xd4\xc0\xd3\xb0\xa1\xb5\xe5 \xbd\xc7\xc7\xe0 \xc1\xdf \xbf\xa1\xb7\xaf\xb0\xa1 \xb9\xdf\xbb\xfd\xc7\xcf\xbf\xb4\xbd\xc0\xb4\xcf\xb4\xd9. \xb0\xd4\xc0\xd3 \xc6\xfa\xb4\xf5 \xbe\xc8\xc0\xc7 GameGuard \xc6\xfa\xb4\xf5\xbf\xa1 \xc0\xd6\xb4\xc2 *.erl \xc6\xc4\xc0\xcf\xb5\xe9\xc0\xbb game1@inca.co.kr\xb7\xce \xc3\xb7\xba\xce\xc7\xcf\xbf\xa9 \xb8\xde\xc0\xcf \xba\xb8\xb3\xbb\xc1\xd6\xbd\xc3\xb1\xe2 \xb9\xd9\xb6\xf8\xb4\xcf\xb4\xd9";
		sprintf(m_buffer, " (%d).", error);
		m_errorMessages[error] += m_buffer;
	}
	message = m_errorMessages[error];
}

bool GGC_Helper::GetFirstCriticalErrorMessage(unsigned long& error,
	std::string& message)
{
	if (GetCriticalErrorCount() == 0)
		return false;
	error = m_criticalErrors.front();
	GetErrorMessage(error, message);
	return true;
}

void GGC_Helper::ForceShutdown()
{
	g_bQuit = true;
	if (WNetworkSystem::Instance())
	{
		if (WNetworkSystem::Instance()->IsConnected(WNetworkSystem::NET_GAME))
			WNetworkSystem::Instance()->ForceShutDown(WNetworkSystem::NET_GAME);
		if (WNetworkSystem::Instance() &&
			WNetworkSystem::Instance()->IsConnected(WNetworkSystem::NET_LOGIN))
			WNetworkSystem::Instance()->ForceShutDown(
				WNetworkSystem::NET_LOGIN);
	}
}

void GGC_Helper::Reset()
{
	m_approvableErrors.clear();
	m_criticalErrors.clear();
}

bool GGC_Helper::OnGameGuardDlgResult(int result, FrForm* form)
{
	ForceShutdown();
	return true;
}
