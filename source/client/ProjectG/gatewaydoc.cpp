void CGolfItemDoc::ResetCalipersVariable()
{
	m_calipersCount = 0;
	EnableCalipers(false);
}

void CGolfItemDoc::DeceaseCalipersCount()
{
	if (m_calipersCount <= 0)
	{
		m_calipersCount = 0;
	}
	else

		m_calipersCount--;
}

